-- Request-level demo fares with durable payment and settlement identities.
-- Existing trip-based mock payments remain available to historical readers.
CREATE TABLE ride_fare_quotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES service_requests(id),
    trip_id bigint REFERENCES trips(id),
    route_revision_id bigint UNIQUE REFERENCES route_revisions(id),
    distance_m bigint NOT NULL CHECK (distance_m > 0),
    duration_s integer NOT NULL CHECK (duration_s > 0),
    tariff_version text NOT NULL,
    amount_minor bigint NOT NULL CHECK (amount_minor >= 0),
    currency_code text NOT NULL,
    quoted_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL CHECK (expires_at > quoted_at),
    accepted_at timestamptz,
    CHECK ((trip_id IS NULL) = (route_revision_id IS NULL)),
    UNIQUE (id, request_id)
);

CREATE UNIQUE INDEX ux_ride_initial_quote ON ride_fare_quotes (request_id)
    WHERE route_revision_id IS NULL;

CREATE TABLE ride_payment_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id bigint NOT NULL REFERENCES ride_fare_quotes(id),
    attempt_key text NOT NULL CHECK (length(attempt_key) BETWEEN 1 AND 128),
    method_ref text NOT NULL,
    amount_minor bigint NOT NULL CHECK (amount_minor > 0),
    result text NOT NULL CHECK (result IN ('SUCCEEDED', 'FAILED')),
    attempted_at timestamptz NOT NULL,
    UNIQUE (quote_id, attempt_key)
);

CREATE UNIQUE INDEX ux_ride_payment_success ON ride_payment_attempts (quote_id)
    WHERE result = 'SUCCEEDED';

CREATE TABLE ride_fare_settlements (
    trip_id bigint PRIMARY KEY REFERENCES trips(id),
    request_id bigint NOT NULL UNIQUE REFERENCES service_requests(id),
    quote_id bigint NOT NULL,
    alighting_check_id bigint NOT NULL UNIQUE REFERENCES passenger_checks(id),
    amount_minor bigint NOT NULL CHECK (amount_minor >= 0),
    currency_code text NOT NULL,
    receipt_ref text NOT NULL UNIQUE,
    finalized_at timestamptz NOT NULL,
    FOREIGN KEY (quote_id, request_id) REFERENCES ride_fare_quotes(id, request_id)
);
