-- Captures a local replay's facility use separately from the passenger trip.
CREATE TABLE demo_depot_cycles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id bigint NOT NULL REFERENCES vehicles(id),
    dispatch_id bigint UNIQUE REFERENCES dispatches(id),
    request_id bigint UNIQUE REFERENCES service_requests(id),
    place_id bigint NOT NULL REFERENCES places(id),
    facility_use_id bigint UNIQUE REFERENCES facility_uses(id),
    phase text NOT NULL CHECK (phase IN
        ('INITIAL', 'RETURNING', 'ARRIVED', 'OCCUPIED', 'CHARGING', 'WAITING', 'VACATED')),
    charge_started_at timestamptz,
    battery_pct double precision CHECK (battery_pct BETWEEN 0 AND 100),
    CHECK ((dispatch_id IS NULL) = (request_id IS NULL))
);

CREATE UNIQUE INDEX ux_demo_initial_depot_cycle ON demo_depot_cycles (vehicle_id)
    WHERE dispatch_id IS NULL;
CREATE UNIQUE INDEX ux_demo_open_depot_cycle ON demo_depot_cycles (vehicle_id)
    WHERE phase <> 'VACATED';
