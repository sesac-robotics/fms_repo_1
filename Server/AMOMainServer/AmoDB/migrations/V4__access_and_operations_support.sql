CREATE SEQUENCE amo_record_id START WITH 10000;

CREATE TABLE amo_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_user_id bigint UNIQUE REFERENCES users(id),
    email text NOT NULL UNIQUE CHECK (email = lower(email)),
    name text NOT NULL,
    password_hash text,
    role text NOT NULL CHECK (role IN ('ADMIN', 'OPERATOR', 'PASSENGER')),
    status text NOT NULL CHECK (status IN ('ACTIVE', 'PENDING', 'SUSPENDED')),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((role = 'PASSENGER') = (profile_user_id IS NOT NULL))
);

CREATE TABLE amo_provider_links (
    issuer text NOT NULL,
    subject text NOT NULL,
    account_id bigint NOT NULL REFERENCES amo_accounts(id),
    PRIMARY KEY (issuer, subject),
    UNIQUE (account_id, issuer)
);

CREATE TABLE amo_sessions (
    id uuid PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES amo_accounts(id),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz
);

CREATE INDEX ix_amo_sessions_account ON amo_sessions(account_id);

CREATE TABLE amo_admin_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL REFERENCES amo_accounts(id),
    member_id bigint REFERENCES amo_accounts(id),
    action text NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE amo_menu (
    key text PRIMARY KEY,
    label_ko text NOT NULL CHECK (length(btrim(label_ko)) > 0),
    label_en text NOT NULL CHECK (length(btrim(label_en)) > 0),
    label_zh text NOT NULL CHECK (length(btrim(label_zh)) > 0),
    visible boolean NOT NULL,
    position integer NOT NULL CHECK (position >= 0)
);

